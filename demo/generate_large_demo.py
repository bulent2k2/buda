    ("c0sm_", "u_cpu0", "u_sec",    8, 2),
    ("c1sm_", "u_cpu1", "u_sec",    8, 2),
    ("c0pm_", "u_cpu0", "u_pcie",   8, 1),
    ("c0um_", "u_cpu0", "u_usb",    8, 1),
